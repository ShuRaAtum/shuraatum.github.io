#!/usr/bin/env python3
"""Refresh _data/citations.yml from the public Google Scholar profile.

Usage (from the repo root):  python3 scripts/update_citations.py

Reads `scholar_userid` from _data/socials.yml, fetches the profile page
(up to 100 papers), and rewrites _data/citations.yml with per-paper citation
counts plus profile totals (citations, h-index, i10-index). Paper keys are
`<user>:<paper id>`, which is what `google_scholar_id` in papers.bib points at.

Google Scholar rate-limits automated requests. Run this by hand now and then;
if it gets an empty or blocked page, it exits without touching the file.
"""

import datetime
import html
import pathlib
import re
import sys
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOCIALS = ROOT / "_data" / "socials.yml"
OUT = ROOT / "_data" / "citations.yml"
UA = "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/131.0 Safari/537.36"


def scholar_user() -> str:
    m = re.search(r"^scholar_userid:\s*['\"]?([\w-]+)", SOCIALS.read_text(encoding="utf-8"), re.M)
    if not m:
        sys.exit("scholar_userid not found in _data/socials.yml")
    return m.group(1)


def fetch(user: str) -> str:
    url = f"https://scholar.google.com/citations?user={user}&hl=en&cstart=0&pagesize=100"
    req = urllib.request.Request(url, headers={"User-Agent": UA, "Accept-Language": "en"})
    with urllib.request.urlopen(req, timeout=30) as r:
        return r.read().decode("utf-8", "replace")


def q(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main() -> None:
    user = scholar_user()
    page = fetch(user)
    rows = re.findall(r'<tr class="gsc_a_tr">(.*?)</tr>', page, re.S)
    stats = re.findall(r'<td class="gsc_rsb_std">(\d+)</td>', page)
    if not rows or len(stats) < 6:
        sys.exit("Scholar returned no data (probably rate-limited); citations.yml left unchanged.")

    lines = [
        "# Generated by scripts/update_citations.py from Google Scholar. Do not edit by hand.",
        "metadata:",
        f"  last_updated: '{datetime.date.today().isoformat()}'",
        f"  total_citations: {stats[0]}",
        f"  h_index: {stats[2]}",
        f"  i10_index: {stats[4]}",
        "papers:",
    ]
    for row in rows:
        pid = re.search(rf"citation_for_view={user}:([^\"&]+)", row)
        title = re.search(r'class="gsc_a_at"[^>]*>(.*?)</a>', row, re.S)
        cites = re.search(r'class="gsc_a_ac gs_ibl"[^>]*>(\d*)<', row)
        year = re.search(r'class="gsc_a_h gsc_a_hc gs_ibl"[^>]*>(\d*)<', row)
        if not pid or not title:
            continue
        lines += [
            f"  {user}:{pid.group(1)}:",
            f"    citations: {int(cites.group(1)) if cites and cites.group(1) else 0}",
            f"    title: {q(html.unescape(re.sub(r'<.*?>', '', title.group(1))))}",
            f"    year: '{year.group(1) if year and year.group(1) else ''}'",
        ]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {len(rows)} papers to {OUT.relative_to(ROOT)} ({stats[0]} citations, h-index {stats[2]}).")


if __name__ == "__main__":
    main()
